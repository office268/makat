"""תחילית המק"ט המקורי אומרת איזה חלק זה, ולפעמים היא סותרת את המבוקש.

‏``validate`` בודקת שהמק"ט שייך ליצרן הרכב הנכון ושהמודל היה בטוח. היא
לא בודקת דבר אחד: שהמק"ט הוא באמת של *סוג החלק שביקשנו*. מק"ט טויוטה
תקין לחלוטין, בביטחון גבוה, בלי אזכור של יצרן אחר - ופשוט של חלק אחר.

זו לא אפשרות תיאורטית. בגיליון של 2,689 מק"טים שנשלפו בפועל היו 150
שורות כאלה, וכולן עברו את האימות:

  * ‏AURIS · air_filter · 43512-02250 - ‏43512 הוא דיסק בלם קדמי.
  * ‏ספורטאז' · brake_pads_front · 58302-... - ‏58302 הוא רפידות *אחוריות*.

השנייה מסוכנת יותר מהראשונה. מסנן אוויר שהוא דיסק בלם הוא שגיאה
שמתגלה בהזמנה; רפידות אחוריות שנמכרו כקדמיות מתגלות במוסך, אחרי שמישהו
שילם והרכיב.

**הטבלה היא לפי תחילית, לא לפי יצרן, ובכוונה.** אותה נתונים מראים
ש-``15208`` (נִיסאן) ו-``26300`` (יונדאי/קיה) מופיעים גם תחת מאזדה,
כי קטלוגים מציגים מק"טים מקבילים בין יצרנים. מה שקבוע הוא *סוג החלק*:
‏15208 הוא מסנן שמן בכל מקום שבו הוא מופיע. ולכן הבדיקה מתעלמת מהיצרן.

**תחילית שאינה בטבלה עוברת.** הטבלה קטנה בכוונה - היא מכסה את החלקים
המתכלים שנשאלים הכי הרבה, ורק תחיליות שיש להן ראיה בנתונים. תחילית
לא מוכרת אינה סתירה, והחמרה כאן הייתה פוסלת מק"טים תקינים.

**תחילית יכולה לשרת כמה סוגים.** ‏``90919`` הוא גם מצת וגם סליל הצתה
בטויוטה, ולכן הערך הוא קבוצה ולא ערך יחיד. פסילה קורית רק כשהתחילית
מוכרת *והסוג המבוקש אינו בקבוצה שלה*.
"""
import re

from .taxonomy import PART_TYPES, type_name

# אורך התחילית. חמישה תווים הוא המבנה של טויוטה, יונדאי/קיה וניסאן
# (‏``43512-02250``). מק"טי מאזדה בנויים אחרת ואינם נכנסים לטבלה, ולכן
# הם פשוט לא מוכרים ועוברים.
PREFIX_LEN = 5

# ‏תחילית -> סוגי החלק שהיא משרתת. נבנתה מ-2,689 מק"טים שנשלפו בפועל,
# והתחיליות כאן הן אלה שחזרו בעקביות בשורות שהגיעו *מקטלוג היצרן לפי
# מספר שלדה* - כלומר מתוך תרשים פיצוץ אמיתי, ולא מהצלבה.
PREFIXES = {
    # בלמים - כאן ההבחנה קדמי/אחורי היא כל העניין
    "04465": ("brake_pads_front",),
    "04466": ("brake_pads_rear",),
    "58101": ("brake_pads_front",),
    "58302": ("brake_pads_rear",),
    "43512": ("brake_disc_front",),
    "42431": ("brake_disc_rear",),
    "51712": ("brake_disc_front",),
    "58411": ("brake_disc_front",),
    # מסנני שמן
    "90915": ("oil_filter",),
    "04152": ("oil_filter",),
    "26300": ("oil_filter",),
    "15208": ("oil_filter",),
    "15400": ("oil_filter",),
    # מסנני אוויר
    "17801": ("air_filter",),
    "28113": ("air_filter",),
    "16546": ("air_filter",),
    # מסנני מזגן
    "87139": ("cabin_filter",),
    "97133": ("cabin_filter",),
    "27277": ("cabin_filter",),
    # הצתה - תחילית אחת לשני סוגים, וזו הסיבה שהערך הוא קבוצה
    "90919": ("spark_plug", "ignition_coil"),
}

_CLEAN = re.compile(r"[^0-9A-Za-z]")


def prefix_of(part_number):
    """התחילית המנורמלת, בלי מקפים ורווחים."""
    return _CLEAN.sub("", str(part_number or "")).upper()[:PREFIX_LEN]


def types_for(part_number):
    """סוגי החלק שהתחילית משרתת, או ``()`` כשהיא לא מוכרת."""
    return PREFIXES.get(prefix_of(part_number), ())


def conflict(part_number, part_type):
    """סוג החלק שהתחילית באמת שייכת לו, כשהיא סותרת את המבוקש.

    ‏``None`` בכל מקרה אחר: תחילית לא מוכרת, סוג חלק לא מוכר, או
    התאמה. הבדיקה שותקת יותר משהיא מדברת, וזה מכוון.
    """
    known = types_for(part_number)
    if not known or part_type not in PART_TYPES:
        return None
    if part_type in known:
        return None
    return known[0]


def explain(part_number, part_type):
    """סיבת הפסילה בעברית, או ``None`` כשאין סתירה."""
    clash = conflict(part_number, part_type)
    if not clash:
        return None
    return (f'תחילית {prefix_of(part_number)} היא של '
            f'{type_name(clash)}, לא {type_name(part_type)}')
